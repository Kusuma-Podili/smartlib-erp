def lookup_cutter_number(author_surname: str) -> str:
    """Generate a 3-figure Cutter-Sanborn author number for shelf classification."""
    clean = author_surname.strip().lower()
    if not clean:
        return "C100"

    first_char = clean[0].upper()
    best_match = "100"

    # Match longest prefix
    for length in range(len(clean), 0, -1):
        sub = clean[:length]
        if sub in CUTTER_TABLE:
            best_match = CUTTER_TABLE[sub]
            break

    return f"{first_char}{best_match}"


def format_call_number(classification: str, author_surname: str, publication_year: Optional[int] = None) -> str:
    """Combine Dewey/LCC classification, Cutter author mark, and year into call number."""
    cutter = lookup_cutter_number(author_surname)
    if publication_year:
        return f"{classification.strip()} .{cutter} {publication_year}"
    return f"{classification.strip()} .{cutter}"
